# =====================================
# validate.ps1
#
# Responsibilities
# - Validate CSV files
# - Validate CSV schema
# - Reject orphaned PBIP local date variation tables
# =====================================

$ErrorActionPreference = "Stop"

Write-Host "Starting validation..."

$requiredDirectories = @(
    "src/Core",
    "src/Core/Models",
    "src/Core/Serialization",
    "data"
)

foreach ($directory in $requiredDirectories) {
    if (Test-Path $directory) {
        Write-Host "Validated directory: $directory"
    } else {
        Write-Host "Missing directory: $directory"
    }
}

$requiredFiles = @(
    "src/Core/SchemaReader.cs",
    "src/Core/ModelBuilder.cs",
    "src/Core/Serialization/JsonSerializer.cs",
    "src/Core/Serialization/SerializerExtensions.cs"
)

foreach ($file in $requiredFiles) {
    if (Test-Path $file) {
        Write-Host "Validated file: $file"
    } else {
        Write-Host "Missing file: $file"
    }
}

# PBIP semantic models generated by this repository do not create
# Power BI auto-date LocalDateTable variations. Such tables require
# variation target metadata and can make Power BI Desktop reject the PBIP.
$pbipSemanticModelRoots = @(
    "pbip/Pipeline_SLA_Tracker.SemanticModel",
    "BuildResult/PBIP/Pipeline_SLA_Tracker.SemanticModel"
)

foreach ($semanticModelRoot in $pbipSemanticModelRoots) {
    if (!(Test-Path $semanticModelRoot)) {
        continue
    }

    $orphanedLocalDateTables = Get-ChildItem -Path $semanticModelRoot -Recurse -Filter "LocalDateTable_*.tmdl" -File -ErrorAction SilentlyContinue

    if ($orphanedLocalDateTables.Count -gt 0) {
        $paths = $orphanedLocalDateTables | ForEach-Object { $_.FullName }
        throw "PBIP validation failed: orphaned LocalDateTable variation tables were found under '$semanticModelRoot':`n - $($paths -join "`n - ")"
    }

    Write-Host "Validated PBIP semantic model: no orphaned LocalDateTable variations found in $semanticModelRoot"
}

Write-Host "Validation complete."
exit 0
