# =====================================
# validate.ps1
#
# Responsibilities
# - Validate CSV files
# - Validate CSV schema
# - Reject orphaned PBIP local date variation tables
# =====================================

$ErrorActionPreference = "Stop"

Write-Host "Starting validation..."

$requiredDirectories = @(
    "src/Core",
    "src/Core/Models",
    "src/Core/Serialization",
    "data"
)

foreach ($directory in $requiredDirectories) {
    if (Test-Path $directory) {
        Write-Host "Validated directory: $directory"
    } else {
        Write-Host "Missing directory: $directory"
    }
}

$requiredFiles = @(
    "src/Core/SchemaReader.cs",
    "src/Core/ModelBuilder.cs",
    "src/Core/Serialization/JsonSerializer.cs",
    "src/Core/Serialization/SerializerExtensions.cs"
)

foreach ($file in $requiredFiles) {
    if (Test-Path $file) {
        Write-Host "Validated file: $file"
    } else {
        Write-Host "Missing file: $file"
    }
}

# PBIP semantic models generated by this repository preserve the required
# Power BI LocalDateTable variation tables. They must remain fully related
# and loadable because Desktop resolves date-column variations through them.
$pbipSemanticModelRoots = @(
    "pbip/Pipeline_SLA_Tracker.SemanticModel",
    "BuildResult/PBIP/Pipeline_SLA_Tracker.SemanticModel"
)

foreach ($semanticModelRoot in $pbipSemanticModelRoots) {
    if (!(Test-Path $semanticModelRoot)) {
        continue
    }

    $tablesRoot = Join-Path $semanticModelRoot "definition/tables"

    $localDateTables = @(
        Get-ChildItem `
            -Path $tablesRoot `
            -Filter "LocalDateTable_*.tmdl" `
            -File `
            -ErrorAction SilentlyContinue
    )

    if ($localDateTables.Count -eq 0) {
        Write-Host "Validated PBIP semantic model: no LocalDateTable variations in $semanticModelRoot"
        continue
    }

    $relationshipsPath = Join-Path $semanticModelRoot "definition/relationships.tmdl"

    $relationshipsContent = if (Test-Path $relationshipsPath) {
        Get-Content $relationshipsPath -Raw
    }
    else {
        ""
    }

    $orphaned = @(
        $localDateTables | Where-Object {
            $tableName = $_.BaseName

            $relationshipsContent -notmatch (
                [regex]::Escape($tableName) + "\."
            )
        }
    )

    if ($orphaned.Count -gt 0) {
        $paths = $orphaned | ForEach-Object { $_.FullName }

        throw @"
PBIP validation failed: orphaned LocalDateTable variation tables were found under '$semanticModelRoot' (no matching relationship):
 - $($paths -join "`n - ")
"@
    }

    Write-Host "Validated PBIP semantic model: all $($localDateTables.Count) LocalDateTable variation(s) in $semanticModelRoot are properly related"
}
Write-Host "Validation complete."
exit 0
